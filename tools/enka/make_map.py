"""Builds src/data/enkaMap.js: Enka.Network's ZZZ IDs → this site's ids.

Run after a game update (needs a checkout of github.com/EnkaNetwork/API-docs):
    python3 tools/enka/make_map.py /path/to/API-docs
Agents, W-Engines and Drive Disc sets are matched by their English names;
anything unmatched is printed so it can go in OVERRIDES below.
"""
import json, re, sys, subprocess, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
STORE = pathlib.Path(sys.argv[1]) / 'store' / 'zzz'
load = lambda f: json.loads((STORE / f).read_text())
EN = load('locs.json')['en']

# Names that don't match by their text (Enka name → site id).
OVERRIDES = {
    'agents': {
        'Starlight - Billy': 'starlight-billy-kid', 'Roxy': 'roxy-ifrita-pryce', 'Phoenix': 'phoenix-reffaella',
        'Harumasa': 'asaba-harumasa', 'Lucy': 'luciana-de-montefio', 'Lycaon': 'von-lycaon', 'Manato': 'komano-manato',
        'Miyabi': 'hoshimi-miyabi', 'Nekomata': 'nekomiya-mana', 'Orphie & Magus': 'orphie-magnusson-and-magus',
        'Rina': 'alexandrina-sebastiane', 'Yanagi': 'tsukishiro-yanagi', 'Yuzuha': 'ukinami-yuzuha',
    },
    'weapons': {},
    'sets': {},
}

def site(kind):
    """[(id, name)] from the site's data, read with bun (the data files are JS)."""
    js = {
        'agents': "import { AGENTS as X } from './src/data/agents.js';",
        'weapons': "import { W_ENGINES as X } from './src/data/wEngines.js';",
        'sets': "import { DRIVE_DISC_SETS as X } from './src/data/driveDiscs.js';",
    }[kind] + " console.log(JSON.stringify(X.map((x) => [x.id, x.name])));"
    out = subprocess.run(['/root/.bun/bin/bun', '-e', js], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return json.loads(out)

norm = lambda s: re.sub(r'[^a-z0-9]', '', s.lower().replace('&', 'and'))

def match(kind, enka):
    """enka: {enkaId: englishName} → ({enkaId: siteId}, unmatched names)."""
    rows = site(kind)
    by = {norm(n): i for i, n in rows}
    firsts = {}
    for i, n in rows:  # Agents: Enka often uses just the first name ("Cissia", "Norma").
        firsts.setdefault(norm(n.split(' ')[0]), []).append(i)
    out, miss = {}, []
    for eid, name in enka.items():
        if not name:
            continue
        sid = OVERRIDES[kind].get(name) or by.get(norm(name))
        if not sid and kind == 'agents' and len(firsts.get(norm(name), [])) == 1:
            sid = firsts[norm(name)][0]
        if sid:
            out[eid] = sid
        else:
            miss.append(name)
    return out, miss

avatars = {k: EN.get(v['Name'], '') for k, v in load('avatars.json').items()}
weapons = {k: EN.get(v['ItemName'], '') for k, v in load('weapons.json').items() if v.get('Rarity', 0) >= 3}
suits = {k: EN.get(v['Name'], '') for k, v in load('equipments.json')['Suits'].items()}

A, am = match('agents', avatars)
W, wm = match('weapons', weapons)
S, sm = match('sets', suits)
for kind, m in [('agents', am), ('W-Engines', wm), ('sets', sm)]:
    if m:
        print(f'Unmatched {kind}:', ', '.join(sorted(m)))

# Disc item id → set id: Enka gives each disc an item id; its suit is SuitId.
items = {k: v['SuitId'] for k, v in load('equipments.json')['Items'].items()}

header = f'''// Enka.Network ZZZ IDs → this site's ids, for "Import from UID".
// Generated by tools/enka/make_map.py from github.com/EnkaNetwork/API-docs (store/zzz).
// Re-run after a game update; don't edit by hand.
'''
body = (
    header
    + f'export const ENKA_AGENTS = {json.dumps(A, sort_keys=True)};\n'
    + f'export const ENKA_WEAPONS = {json.dumps(W, sort_keys=True)};\n'
    + f'export const ENKA_SETS = {json.dumps(S, sort_keys=True)};\n'
    + '/** Disc item id → its set\'s Enka id (SuitId); the set id is the item id with the last 2 digits as 00. */\n'
)
(ROOT / 'src/data/enkaMap.js').write_text(body)
print(f'agents {len(A)}/{len([v for v in avatars.values() if v])} · W-Engines {len(W)}/{len([v for v in weapons.values() if v])} · sets {len(S)}/{len(suits)}')
# Check the SuitId rule holds, so the map needn't list every disc.
bad = [k for k, s in items.items() if int(k) // 100 * 100 != s]
print('disc ids not following the set rule:', bad[:5])
