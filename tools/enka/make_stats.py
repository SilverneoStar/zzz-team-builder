"""Agent base stats at Lv.60 (+ Core Skill bonuses) for the Stat progress estimate.

Reads store/zzz/avatars.json from a checkout of github.com/EnkaNetwork/API-docs
and writes src/data/agentStats.js. Re-run after a game update:

    python3 tools/enka/make_stats.py /path/to/API-docs
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
docs = sys.argv[1] if len(sys.argv) > 1 else '/tmp/enkadocs'
avatars = json.load(open(os.path.join(docs, 'store/zzz/avatars.json')))
amap = json.loads(re.search(r'ENKA_AGENTS = (\{.*?\});', open(os.path.join(ROOT, 'src/data/enkaMap.js')).read()).group(1))

# Enka property id -> short key. CRIT and ER come in hundredths (500 = 5%, 120 = 1.2).
KEYS = {'11101': 'hp', '12101': 'atk', '13101': 'def', '12201': 'impact', '20101': 'critRate', '21101': 'critDmg',
        '31401': 'am', '31201': 'ap', '30501': 'er', '11102': 'hpPct', '12102': 'atkPct', '23101': 'penRatio'}
LEVEL, PROMO = 60, 5  # Lv.60 is promotion level 6 (index 5)

out = {}
for eid, a in avatars.items():
    aid = amap.get(eid)
    if not aid:
        continue
    base = {}
    for pid, v in a['BaseProps'].items():
        k = KEYS.get(pid)
        if not k:
            continue
        grow = (a['GrowthProps'].get(pid, 0) * (LEVEL - 1)) // 10000
        promo = a['PromotionProps'][PROMO].get(pid, 0)
        base[k] = v + grow + promo
    core = [{KEYS[p]: v for p, v in c.items() if p in KEYS and v} for c in a['CoreEnhancementProps']]
    out[aid] = {'base': base, 'core': core}

with open(os.path.join(ROOT, 'src/data/agentStats.js'), 'w') as f:
    f.write('// Agent stats at Lv.60 before gear, and what each Core Skill level (None, A–F) adds.\n')
    f.write('// Generated by tools/enka/make_stats.py from github.com/EnkaNetwork/API-docs (store/zzz).\n')
    f.write('// CRIT Rate/DMG are in hundredths of a percent (500 = 5%), Energy Regen in hundredths (120 = 1.2).\n')
    f.write('export const AGENT_STATS = {\n')
    for k in sorted(out):
        f.write(f'  {json.dumps(k)}: {json.dumps(out[k], separators=(",", ":"))},\n')
    f.write('};\n')
print(len(out), 'Agents')
